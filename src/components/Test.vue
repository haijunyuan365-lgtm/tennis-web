        BALL_RADIUS: 0.03175,
        baselines_z: 11.885,
        double_sidelines_x: 5.485,
      },
      x: 0,
      z: 0,
      realOut: false,
      passedCoordinatesCount: 0,
      tennisBall: {
        position: new THREE.Vector3()
      },
      distance:0,
      currentRound:0,
    }
  },

  props:['receiveInitialTrajectoryPoints','receiveRealOut','receiveDistance'],

  mounted() {
    const storedRoundId = localStorage.getItem("roundId")-1;
      
    if (storedRoundId !== null && !isNaN(storedRoundId)) {
      this.currentRound = parseInt(storedRoundId);
    } else {
      this.currentRound = 0;
    }
    this.loadInitialTrajectory();
    this.simulateCollisionCheck();
  },


  methods: {
    loadInitialTrajectory() {
      this.trajectoryPoints = this.initialTrajectoryPoints[this.currentRound].map(p => 
        new THREE.Vector3(p[0], p[1], p[2])
      );
    },

    simulateCollisionCheck() {
      // 找出最低点（碰撞点）
      let minY = Infinity;
      let minIndex = -1;
      
      for (let i = 0; i < this.trajectoryPoints.length; i++) {
        const point = this.trajectoryPoints[i];
        if (point.y < minY) {
          minY = point.y;
          minIndex = i;
        }
      }
      
      // 只在最低点执行碰撞检测
      if (minIndex >= 0) {
        const point = this.trajectoryPoints[minIndex];
        this.passedCoordinatesCount = minIndex;
        
        // 计算方向向量
        const prevIndex = Math.max(0, minIndex - 1);
        const direction = new THREE.Vector3().subVectors(
          point, 
          this.trajectoryPoints[prevIndex]
        ).normalize();
        
        // 执行碰撞检查并更新轨迹
        this.checkCollisionAndUpdateTrajectory(
          point.x, 
          point.z, 
          direction
        );
      }
      
      // 所有点处理完成后，输出更新后的轨迹
      console.log("更新后的轨迹点数组:", this.trajectoryPoints);
      this.receiveInitialTrajectoryPoints(this.trajectoryPoints);
      this.receiveRealOut(this.realOut)
      this.receiveDistance(this.distance)
    },

    checkCollisionAndUpdateTrajectory(x, z, direction) {
      this.x = x;
      this.z = z;
      
      // 最大迭代次数，防止无限循环
      const maxIterations = 1000;
      let iteration = 0;
      let isConsistent = false;
       // 计算包围盒
      let minMax = { minX: Infinity, maxX: -Infinity, minZ: Infinity, maxZ: -Infinity };
      
      while (!isConsistent && iteration < maxIterations) {
        iteration++;
        
        // 检查方向有效性
        if (direction.length() < 0.001) {
          direction = new THREE.Vector3(1, 0, 0);
        }

        // 计算椭圆尺寸
        const majorAxis = this.constants.BALL_RADIUS * 1.0;
        const minorAxis = this.constants.BALL_RADIUS * 0.8;

        // 创建椭圆形阴影（仅用于计算）
        const shadowGeometry = new THREE.EllipseCurve(
          0, 0, majorAxis, minorAxis, 0, Math.PI * 2, false, 0
        );
        
        const points = shadowGeometry.getPoints(32);
        
        // === 检查是否出界 ===
        let isOutOfBounds = false;
        const angle = Math.atan2(direction.z, direction.x);
        const rotationAngle = -angle + Math.PI;
        
        // 计算包围盒
        minMax = { minX: Infinity, maxX: -Infinity, minZ: Infinity, maxZ: -Infinity };
        
        points.forEach(point => {
          // 应用2D旋转变换
          const xWorld = this.x + 
                        point.x * Math.cos(rotationAngle) - 
                        point.y * Math.sin(rotationAngle);
          
          const zWorld = this.z + 
                        point.x * Math.sin(rotationAngle) + 
                        point.y * Math.cos(rotationAngle);
          
          minMax.minX = Math.min(minMax.minX, xWorld);
          minMax.maxX = Math.max(minMax.maxX, xWorld);
          minMax.minZ = Math.min(minMax.minZ, zWorld);
          minMax.maxZ = Math.max(minMax.maxZ, zWorld);
        });
        
        // 检测是否出界
        const court = this.constants;
        if (
            Math.abs(minMax.minX) > court.double_sidelines_x ||
            Math.abs(minMax.minZ) > court.baselines_z 
        ) {
            isOutOfBounds = true;
        }

        // 判断条件
        if (isOutOfBounds !== this.realOut) {
          // 调整球位置
          this.adjustPosition(direction, this.realOut);
        } else {
          isConsistent = true;
        }
      }

      // 安全计算距离
      if (minMax) {
        const xDist = Math.abs(minMax.minX) - this.constants.double_sidelines_x;
        const zDist = Math.abs(minMax.minZ) - this.constants.baselines_z;
        
        // 避免 NaN
        this.distance = Math.min(
          isFinite(xDist) ? Math.abs(xDist) : Infinity,
          isFinite(zDist) ? Math.abs(zDist) : Infinity
        );
      } else {
        this.distance = Infinity;
      }

      if (iteration >= maxIterations) {
        console.warn("达到最大迭代次数，可能无法满足条件");
      }
      
      // 更新轨迹数组中的点
      this.updateTrajectoryPoint();
    },
    
    updateTrajectoryPoint() {
      if (this.trajectoryPoints.length > 0 && 
          this.passedCoordinatesCount >= 0 && 
          this.passedCoordinatesCount < this.trajectoryPoints.length) {
        
        // 获取当前轨迹点
        const point = this.trajectoryPoints[this.passedCoordinatesCount];
        
        // 更新x和z坐标（保持y不变）
        point.x = this.x;
        point.z = this.z;
        //如果误差很大，那么就以后的每个点都加上这个差值

        // point.x += 0.01;
        // point.z += 0.01;
        
        console.log(`更新点 ${this.passedCoordinatesCount}: (${this.x}, ${point.y}, ${this.z})`);
      }
    },
    
    adjustPosition(direction, realOut) {
      if (direction) {
        // 使用归一化方向向量移动球体
        const moveSpeed = 0.001;

        // 根据期望状态决定移动方向
        const multiplier = realOut ? 1 : -1;

        this.x += direction.x * moveSpeed * multiplier;
        this.z += direction.z * moveSpeed * multiplier;

        // 重新归一化向量
        direction.normalize();
      }
    }
  }
}
</script>

